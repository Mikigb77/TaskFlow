// Writes build/ux/INDEX.md (every PNG: what it shows, its state, sources,
// size and text scale; what isn't covered) and build/ux/AUDIT.md (the
// measured evidence for each screen and state), from the areas' manifests.
import 'dart:convert';
import 'dart:io';

import 'audit.dart' show dpToMm, minGap, minTarget, primaryWatch;
import 'preview.dart';

typedef _Shot = Map<String, dynamic>;

final _gap = minGap.round();
final _target = minTarget.round();

/// Writes both files from every area manifest under build/ux/.
void writeReports({
  required String command,
  required Map<String, String> notCovered,
  required Map<String, String> routes,
}) {
  final areas = <Map<String, dynamic>>[];
  final order = areaTitles.keys.toList();
  final root = Directory(uxRoot);
  if (!root.existsSync()) return;
  for (final dir in root.listSync().whereType<Directory>()) {
    final manifest = File('${dir.path}/manifest.json');
    if (!manifest.existsSync()) continue;
    try {
      areas.add(jsonDecode(manifest.readAsStringSync()) as Map<String, dynamic>);
    } catch (_) {
      // Skipped: a damaged manifest is rewritten when its area renders.
    }
  }
  int rank(Map<String, dynamic> area) {
    final index = order.indexOf(area['area'] as String);
    return index < 0 ? order.length : index;
  }

  areas.sort((a, b) => rank(a).compareTo(rank(b)));
  final git = _git();
  File('$uxRoot/INDEX.md').writeAsStringSync(
    _index(
      areas,
      command: command,
      git: git,
      notCovered: notCovered,
      routes: routes,
    ),
  );
  File('$uxRoot/AUDIT.md').writeAsStringSync(_audit(areas, git: git));
}

List<_Shot> _shots(Map<String, dynamic> area) =>
    (area['shots'] as List).cast<Map<String, dynamic>>();

String _git() {
  try {
    final head = Process.runSync('git', ['rev-parse', '--short', 'HEAD']);
    final status = Process.runSync('git', [
      'status',
      '--porcelain',
      '--',
      'lib',
      'assets',
    ]);
    final sha = '${head.stdout}'.trim();
    final changed = '${status.stdout}'
        .split('\n')
        .where((line) => line.trim().isNotEmpty)
        .length;
    if (sha.isEmpty) return 'an unknown commit';
    return changed == 0
        ? 'commit `$sha`, with no uncommitted changes under App/lib or App/assets'
        : 'commit `$sha` plus $changed uncommitted change${changed == 1 ? '' : 's'} under App/lib and App/assets (the renders show the working tree)';
  } catch (_) {
    return 'an unknown commit';
  }
}

String _time(String iso) {
  final t = DateTime.tryParse(iso);
  if (t == null) return iso;
  String two(int v) => v.toString().padLeft(2, '0');
  return '${t.year}-${two(t.month)}-${two(t.day)} ${two(t.hour)}:${two(t.minute)}';
}

String _scale(num scale) =>
    scale == scale.roundToDouble() ? '${scale.round()}×' : '$scale×';

String _size(_Shot s) {
  final keyboard = (s['keyboard'] as num? ?? 0) > 0
      ? ' · keyboard ${(s['keyboard'] as num).round()} dp'
      : '';
  return '${(s['width'] as num).round()} × ${(s['height'] as num).round()} dp · '
      '${_scale(s['scale'] as num)} text$keyboard';
}

String _variant(_Shot s) {
  final file = s['file'] as String;
  final parts = file.substring(0, file.length - 4).split('.');
  // <screen>.<state>.<lang>.<theme>.<scale>[.<decimals>]
  return parts.skip(2).join('.');
}

String _cell(Object? text) =>
    '${text ?? ''}'.replaceAll('|', r'\|').replaceAll('\n', ' ');

