// -------------------------------------------------------------------- AUDIT

class _Counts {
  int renders = 0;
  int tap = 0;
  int unlabeled = 0;
  int contrastFlutter = 0;
  int contrastConfirmed = 0;
  int contrastFull = 0;
  int layout = 0;
  int cut = 0;
  int gaps = 0;
  int primary = 0;
  int duplicates = 0;
  int mismatches = 0;
  int errors = 0;

  void add(_Shot s) {
    final a = s['audit'] as Map<String, dynamic>;
    final g = a['guidelines'] as Map<String, dynamic>;
    final flags = a['semanticsFlags'] as Map<String, dynamic>;
    renders++;
    tap += _failures(g['tapTarget']).length;
    unlabeled += (flags['unlabeled'] as List).length;
    for (final f in _failures(g['contrast'])) {
      contrastFlutter++;
      final ours = f['ours'] as num?;
      final required = double.tryParse('${f['required']}') ?? 4.5;
      if (ours == null || ours < required - 0.01) contrastConfirmed++;
    }
    contrastFull += (a['contrast'] as List)
        .where((c) => (c as Map)['disabled'] != true)
        .length;
    layout += (a['layoutErrors'] as List).length;
    cut += (a['text'] as List).length;
    gaps += _smallGaps(a).length;
    primary += _primaries(a).length;
    duplicates += (flags['duplicates'] as List).length;
    mismatches += (flags['mismatches'] as List).length;
    for (final name in ['tapTarget', 'labeled', 'contrast']) {
      if ((g[name] as Map)['error'] != null) errors++;
    }
  }

  String cell(int value) => value == 0 ? '0' : '**$value**';
}

List<Map<String, dynamic>> _failures(Object? guideline) =>
    ((guideline as Map)['failures'] as List).cast<Map<String, dynamic>>();

List<Map<String, dynamic>> _targets(Map<String, dynamic> audit) =>
    (audit['targets'] as List).cast<Map<String, dynamic>>();

List<Map<String, dynamic>> _smallGaps(Map<String, dynamic> audit) => [
  for (final t in _targets(audit))
    if (t['gap'] != null && (t['gap'] as num) < minGap && t['partlyOff'] != true) t,
];

List<Map<String, dynamic>> _primaries(Map<String, dynamic> audit) => [
  for (final t in _targets(audit))
    if (t['primary'] == true &&
        t['partlyOff'] != true &&
        _min(t) >= minTarget &&
        _min(t) < primaryWatch)
      t,
];

double _min(Map<String, dynamic> t) {
  final w = (t['w'] as num).toDouble(), h = (t['h'] as num).toDouble();
  return w < h ? w : h;
}

String _dp(Map<String, dynamic> t) {
  final w = (t['w'] as num).toDouble(), h = (t['h'] as num).toDouble();
  return '${w.toStringAsFixed(0)} × ${h.toStringAsFixed(0)} dp '
      '(${dpToMm(w).toStringAsFixed(1)} × ${dpToMm(h).toStringAsFixed(1)} mm)';
}

/// `«Listo» button`, or `an unlabeled button`.
String _control(Object? label, Object? role) {
  final text = '${label ?? ''}'.trim();
  return text.isEmpty ? 'an unlabeled ${role ?? 'control'}' : '${_name(text)} ${role ?? ''}'.trim();
}

String _name(Object? label, [Object? role]) {
  final text = '${label ?? ''}'.trim();
  if (text.isEmpty) return 'unlabeled ${role ?? 'control'}';
  return '«${text.length > 70 ? '${text.substring(0, 67)}…' : text}»';
}

String _audit(List<Map<String, dynamic>> areas, {required String git}) {
  final out = StringBuffer();
  out.writeln('# Measured evidence for the previews');
  out.writeln();
  out.writeln(
    'Generated with the renders in [INDEX.md](INDEX.md), from $git; don\'t edit '
    'by hand. Every number here was measured on the real widget tree and the '
    'rendered pixels in the Flutter test engine: **widget-test evidence, not a '
    'device**. TalkBack\'s actual speech, a phone\'s fonts and its display can '
    'differ. Problems are recorded, never failed: the run always finishes.',
  );
  out.writeln();
  out.writeln('## How each check works');
  out.writeln();
  out.writeln(
    '1. **Flutter\'s accessibility guidelines**, as `meetsGuideline` runs them: '
    '`androidTapTargetGuideline` (every tappable node at least 48 × 48 dp; it '
    'skips links and nodes touching the screen\'s or a scroll view\'s edge), '
    '`labeledTapTargetGuideline` (every tappable node has a label or tooltip) and '
    '`textContrastGuideline` (WCAG AA: 4.5:1, or 3:1 from 18 px, or 14 px bold). '
    'The contrast guideline uses the style\'s font size before text scaling, and '
    'it only checks text whose semantics label equals a single `Text` — merged '
    'rows such as task tiles are skipped, hence the next check.',
  );
  out.writeln(
    '2. **Full contrast pass** (ours): every line of text on screen. The text '
    'colour comes from its style, blended when translucent; the background is '
    'the commonest colour in the rendered pixels of the line\'s visible box once '
    'the text\'s own colour is set aside (or within 3 dp around it, when the text '
    'fills its box). WCAG AA with the scaled size (large: ≥ 24 dp, or ≥ 18.7 dp '
    'bold). Text read in a disabled control is exempt (WCAG 1.4.3) and listed as '
    'such. Text over an image, a gradient or a shape smaller than the text can '
    'read a wrong background; check those against the PNG.',
  );
  out.writeln(
    '3. **What TalkBack would read**: the semantics tree in traversal order, one '
    'line per node that says or does something, with merged children folded '
    'in: role, label, value, hint, tooltip, states and actions. Indentation '
    'shows nesting. Flags: tappable or button nodes with no label, images with '
    'no label, text fields with neither label nor hint; the same label on more '
    'than one control; and nodes whose spoken words don\'t include the words '
    'they show (WCAG 2.5.3, Label in Name), or that show words TalkBack doesn\'t '
    'read at all. Each line of text is matched to the node TalkBack reads it in, '
    'so a message drawn over a row isn\'t counted, and words are compared one by '
    'one, so bullets and arrows drawn for the eye («X → Y», read «de X a Y») '
    'aren\'t differences. Only text and controls in the route in front are '
    'measured: a page dimmed under a sheet or a dialog is left out.',
  );
  out.writeln(
    '4. **Clipping and layout errors**: every overflow or other layout or build '
    'error reported while rendering, with the app widget that caused it; text '
    'ended by its line limit (ellipsis, fade or clip, by design or not: check the '
    'PNG), lines whose letters reach past the bottom of their box, words split '
    'between two letters because they don\'t fit the width (as a long Catalan '
    'tab label at 2×), text wider than its box, and text that runs past the '
    'screen edge. Text scrolled out of view is not cut. The PNG shows Flutter\'s '
    'yellow-and-black stripe where a layout overflowed.',
  );
  out.writeln(
    '5. **Targets and spacing**: every tappable node on screen with its hit area '
    '(semantics bounds, in dp and mm at 160 dp per inch) and the gap from its '
    'edge to the nearest tappable neighbour. Targets nested in another (a '
    'checkbox in a tappable row) are named with the target around them, not '
    'measured against it. Flags: under $_target dp; gaps under $_gap dp; '
    'and primary actions (filled buttons, FABs) between $_target and '
    '${primaryWatch.round()} dp, since GUIDELINES.md RE-2 and RE-3 ask for clearly '
    'more than 48 dp for older hands (RE-3 aims at about 63 dp). Each gap says '
    'where the neighbour is: rows of a list and tabs of the navigation bar touch '
    'by design (0 dp above, below, left or right), while two buttons side by side '
    'with no gap are what RE-3 warns about. The scrim behind a sheet or dialog '
    '(tap outside to close) is not counted as a target.',
  );
  out.writeln();
  out.writeln(
    'For each screen and state below: the problems of each render (only renders '
    'with something to report), then what TalkBack reads and every target, from '
    'the first render listed (usually Spanish, light, 1× text).',
  );
  out.writeln();
  out.writeln('## Summary');
  out.writeln();
  out.writeln(
    '| Screen · state | Renders | Tap < 48 | No label | Contrast: Flutter (confirmed) · full | '
    'Layout errors | Cut text | Gap < 8 | Primary 48–56 | Same label | '
    'Label ≠ text |',
  );
  out.writeln('|---|---|---|---|---|---|---|---|---|---|---|');
  final groups = <String, List<_Shot>>{};
  final titles = <String, String>{};
  for (final area in areas) {
    for (final s in _shots(area)) {
      final id = '${area['area']}/${s['screen']} · ${s['state']}';
      groups.putIfAbsent(id, () => []).add(s);
      titles[id] = '${s['screenTitle']}';
    }
  }
  final totals = _Counts();
  for (final entry in groups.entries) {
    final counts = _Counts();
    for (final s in entry.value) {
      counts.add(s);
      totals.add(s);
    }
    out.writeln(
      '| [${entry.key}](#${_anchor(entry.key)}) | ${counts.renders} | '
      '${counts.cell(counts.tap)} | ${counts.cell(counts.unlabeled)} | '
      '${counts.contrastFlutter} (${counts.cell(counts.contrastConfirmed)}) · ${counts.cell(counts.contrastFull)} | '
      '${counts.cell(counts.layout)} | ${counts.cell(counts.cut)} | '
      '${counts.cell(counts.gaps)} | ${counts.cell(counts.primary)} | '
      '${counts.cell(counts.duplicates)} | ${counts.cell(counts.mismatches)} |',
    );
  }
  out.writeln(
    '| **All** | ${totals.renders} | ${totals.tap} | ${totals.unlabeled} | '
    '${totals.contrastFlutter} (${totals.contrastConfirmed}) · ${totals.contrastFull} | ${totals.layout} | '
    '${totals.cut} | ${totals.gaps} | ${totals.primary} | ${totals.duplicates} | '
    '${totals.mismatches} |',
  );
  if (totals.errors > 0) {
    out.writeln();
    out.writeln(
      '${totals.errors} guideline evaluation(s) could not run; see the renders '
      'marked "could not run" below.',
    );
  }
  out.writeln();
  out.writeln(
    'Counts add up every render of the state (a problem in four renders counts '
    'four times). Bold means something to look at. In the contrast column, '
    'Flutter\'s count comes first, then (in brackets) how many of those the '
    'text\'s own colour confirms; Flutter reads the colours from anti-aliased '
    'pixels and often takes a text edge for the text, so the full pass is the '
    'one to trust.',
  );
  out.writeln();
  for (final entry in groups.entries) {
    _section(out, entry.key, titles[entry.key]!, entry.value);
  }
  return out.toString();
}

String _anchor(String heading) => heading
    .toLowerCase()
    .replaceAll(RegExp(r'[^a-z0-9 _-]'), '')
    .trim()
    .replaceAll(' ', '-');

void _section(StringBuffer out, String id, String title, List<_Shot> shots) {
  out.writeln('## $id');
  out.writeln();
  out.writeln(
    '$title. ${shots.first['note'] ?? ''} Renders: '
    '${shots.map((s) => '`${_variant(s)}`').join(', ')}.',
  );
  out.writeln();
  out.writeln('**Problems by render**');
  out.writeln();
  var any = false;
  final listed = <String>{};
  for (final s in shots) {
    final lines = _problems(s['audit'] as Map<String, dynamic>);
    if (lines.isEmpty) continue;
    any = true;
    final fresh = [for (final line in lines) if (!listed.contains(line)) line];
    listed.addAll(lines);
    final repeated = lines.length - fresh.length;
    out.writeln(
      '- `${_variant(s)}`${repeated == 0 ? '' : ' — and $repeated as listed above'}',
    );
    for (final line in fresh) {
      out.writeln('  - $line');
    }
  }
  if (!any) out.writeln('- None measured in any render.');
  out.writeln();
  final first = shots.first;
  final audit = first['audit'] as Map<String, dynamic>;
  out.writeln('**What TalkBack reads** (`${_variant(first)}`)');
  out.writeln();
  final reading = (audit['reading'] as List).cast<Map<String, dynamic>>();
  if (reading.isEmpty) out.writeln('- Nothing.');
  var n = 0;
  for (final node in reading) {
    n++;
    final depth = (node['depth'] as num).toInt();
    final parts = <String>[
      '${node['role']}',
      if ('${node['label']}'.isNotEmpty) '«${node['label']}»' else '(no label)',
      if (node['value'] != null) 'value «${node['value']}»',
      if (node['hint'] != null) 'hint «${node['hint']}»',
      if (node['tooltip'] != null && node['tooltip'] != node['label'])
        'tooltip «${node['tooltip']}»',
      if (node['states'] != null) '[${(node['states'] as List).join(', ')}]',
      if (node['actions'] != null) '→ ${(node['actions'] as List).join(', ')}',
    ];
    out.writeln('${'  ' * depth.clamp(0, 6)}$n. ${parts.join(' ')}');
  }
  out.writeln();
  out.writeln('**Targets** (`${_variant(first)}`)');
  out.writeln();
  final targets = _targets(audit);
  if (targets.isEmpty) {
    out.writeln('- No tappable targets on screen.');
  } else {
    out.writeln('| # | Control | Hit area | Gap to nearest | Notes |');
    out.writeln('|---|---|---|---|---|');
    var i = 0;
    for (final t in targets) {
      i++;
      final notes = <String>[
        if (t['primary'] == true) 'primary',
        if (_min(t) < minTarget) '**under $_target dp**',
        if (t['primary'] == true && _min(t) >= minTarget && _min(t) < primaryWatch)
          '**primary under ${primaryWatch.round()} dp**',
        if (t['gap'] != null && (t['gap'] as num) < minGap) '**gap under $_gap dp**',
        if (t['overlaps'] == true) '**overlaps a neighbour**',
        if (t['inside'] != null) 'inside ${_name(t['inside'])}',
        if (t['partlyOff'] == true) 'partly off screen',
        if (t['disabled'] == true) 'disabled',
      ];
      final gap = t['gap'] == null
          ? '—'
          : '${(t['gap'] as num).toStringAsFixed(0)} dp ${_where(t)}';
      out.writeln(
        '| $i | ${_cell(_control(t['label'], t['role']))} | ${_dp(t)} | '
        '${_cell(gap)} | ${notes.join(', ')} |',
      );
    }
  }
  out.writeln();
}

/// One line per problem in a render.
List<String> _problems(Map<String, dynamic> audit) {
  final lines = <String>[];
  final g = audit['guidelines'] as Map<String, dynamic>;
  for (final name in ['tapTarget', 'labeled', 'contrast']) {
    final error = (g[name] as Map)['error'];
    if (error != null) lines.add('$name guideline could not run: $error');
  }
  for (final f in _failures(g['tapTarget'])) {
    lines.add(
      'androidTapTargetGuideline: ${_control(f['label'], f['role'])} is ${f['size']} dp',
    );
  }
  for (final f in _failures(g['labeled'])) {
    lines.add(
      'labeledTapTargetGuideline: a ${f['role']} at ${f['rect']} has no label (${(f['actions'] as List).join(', ')})',
    );
  }
  for (final f in _failures(g['contrast'])) {
    final ours = f['ours'] as num?;
    final required = double.tryParse('${f['required']}') ?? 4.5;
    final check = ours == null
        ? ''
        : ours >= required - 0.01
        ? ' — the text\'s own colour measures ${ours.toStringAsFixed(2)}:1 here, a pass: '
              'Flutter\'s histogram likely took an anti-aliased edge for the text'
        : ' — confirmed: the text\'s own colour measures ${ours.toStringAsFixed(2)}:1';
    lines.add(
      'textContrastGuideline: ${_name(f['text'])} ${f['found'] ?? '?'}:1, needs '
      '${f['required'] ?? '?'}:1 (font ${f['fontSize'] ?? '?'} before scaling; '
      'colours read ${f['light'] ?? ''} and ${f['dark'] ?? ''})$check',
    );
  }
  for (final c in (audit['contrast'] as List).cast<Map<String, dynamic>>()) {
    lines.add(
      '${c['disabled'] == true ? 'Contrast (disabled, exempt)' : 'Contrast'}: '
      '${_name(c['text'])} ${c['ratio']}:1, needs ${c['required']}:1 '
      '(${c['size']} dp${c['bold'] == true ? ' bold' : ''}; ${c['textColor']} on ${c['background']})',
    );
  }
  final flags = audit['semanticsFlags'] as Map<String, dynamic>;
  for (final u in (flags['unlabeled'] as List).cast<Map<String, dynamic>>()) {
    lines.add(
      'No label: a ${u['role']} at ${u['rect']}${u['actions'] == null ? '' : ' (${(u['actions'] as List).join(', ')})'}',
    );
  }
  for (final d in (flags['duplicates'] as List).cast<Map<String, dynamic>>()) {
    lines.add('Same label on ${d['count']} controls: ${_name(d['label'])}');
  }
  for (final m in (flags['mismatches'] as List).cast<Map<String, dynamic>>()) {
    final shows = (m['shows'] as List).map((s) => _name(s)).join(', ');
    lines.add(
      m['unread'] == true
          ? 'Label ≠ text: TalkBack doesn\'t read $shows (in a ${m['role']} with no label)'
          : 'Label ≠ text: ${m['role']} ${_name(m['label'])} shows $shows',
    );
  }
  for (final e in (audit['layoutErrors'] as List).cast<Map<String, dynamic>>()) {
    lines.add(
      'Layout error: ${e['message']}${e['where'] == null ? '' : ' (`${e['where']}`)'}',
    );
  }
  for (final t in (audit['text'] as List).cast<Map<String, dynamic>>()) {
    lines.add('Cut text: ${_name(t['text'])} — ${t['why']}');
  }
  for (final t in _targets(audit)) {
    if (t['partlyOff'] == true) continue;
    if (_min(t) < minTarget) {
      lines.add('Target under $_target dp: ${_control(t['label'], t['role'])}, ${_dp(t)}');
    }
  }
  for (final t in _primaries(audit)) {
    lines.add('Primary action under ${primaryWatch.round()} dp: ${_name(t['label'])}, ${_dp(t)}');
  }
  for (final t in _smallGaps(audit)) {
    lines.add(
      'Gap under $_gap dp: ${_name(t['label'], t['role'])} is '
      '${(t['gap'] as num).toStringAsFixed(1)} dp ${_where(t)}'
      '${t['overlaps'] == true ? ' (they overlap)' : ''}',
    );
  }
  return lines;
}

/// `below «Comprar pan»`: where the nearest target is.
String _where(Map<String, dynamic> t) {
  final name = _name(t['neighbour']);
  return switch (t['side']) {
    'above' => 'below $name',
    'below' => 'above $name',
    'left' => 'right of $name',
    'right' => 'left of $name',
    'overlapping' => 'overlapping $name',
    _ => 'from $name',
  };
}
