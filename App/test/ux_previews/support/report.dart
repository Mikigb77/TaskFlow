/// Every route the app declares in lib/main.dart, read from the source, so
/// a route added later shows up here as not previewed.
List<String> _declaredRoutes() {
  final file = File('lib/main.dart');
  if (!file.existsSync()) return const [];
  final source = file.readAsStringSync();
  final found = <String>{
    for (final match in RegExp(r"'(/[A-Za-z]*)'\s*:").allMatches(source))
      match.group(1)!,
    for (final match in RegExp(
      r"settings\.name == '(/[A-Za-z]+)'",
    ).allMatches(source))
      match.group(1)!,
  };
  return found.toList()..sort();
}

